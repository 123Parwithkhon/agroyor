/** Экспортируются для тестов полноты переводов. */
export const DICTIONARIES: Record<Lang, Dictionary> = { tj, ru, en };

export type T = (key: DictKey) => string;

export function isLang(value: unknown): value is Lang {
  return typeof value === 'string' && (LANGS as readonly string[]).includes(value);
}

/** Язык из строки document.cookie — для клиентских компонентов (например, error.tsx). */
export function langFromCookieString(cookie: string): Lang {
  const match = new RegExp(`(?:^|;\\s*)${LANG_COOKIE}=([^;]*)`).exec(cookie);
  const value = match?.[1];
  return isLang(value) ? value : DEFAULT_LANG;
}

export function getDictionary(lang: Lang): T {
  const dict = DICTIONARIES[lang];
  return (key) => dict[key];
}

/** Значение атрибута <html lang>: ISO-код таджикского — tg */
export function htmlLang(lang: Lang): string {
  return lang === 'tj' ? 'tg' : lang;
}

/**
 * Название из БД на нужном языке (продукты: name_tj / name_ru / name_en).
 * Если английского названия нет — показываем русское.
 */
export function localizedName(item: { name_tj: string; name_ru: string; name_en: string }, lang: Lang): string {
  if (lang === 'tj') return item.name_tj;
  if (lang === 'en') return item.name_en || item.name_ru;
  return item.name_ru;
}
